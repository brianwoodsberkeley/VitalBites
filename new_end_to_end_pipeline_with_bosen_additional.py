    # Aggregate kg_scores across all target nutrients (same as UI does)
    score_agg = {}
    for raw in info.get("needs", []):
        canonical = nut_norm.get(raw, raw)
        for name, score in predict_head("PROVIDES_BY", canonical, top_k=500):
            score_agg[name] = score_agg.get(name, 0.0) + score

    if len(score_agg) < 20:
        print(f"  {ailment:<30} {'insufficient data':>30}")
        continue

    # Build (kg_score, relevance) pairs
    pairs = []
    for recipe, score in score_agg.items():
        match_count = len(set(kg_nutrients.get(recipe, [])) & target_set)
        pairs.append((score, match_count))

    kg_scores  = [p[0] for p in pairs]
    relevances = [p[1] for p in pairs]


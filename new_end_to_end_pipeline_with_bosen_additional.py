def ndcg_at_k(pairs, k=10):
    """NDCG@k — relevance = number of target nutrients present."""
    top_k = sorted(pairs, key=lambda x: -x[0])[:k]
    dcg   = sum(rel / np.log2(i+2) for i, (_, rel) in enumerate(top_k))
    ideal = sorted([rel for _, rel in top_k], reverse=True)
    idcg  = sum(rel / np.log2(i+2) for i, rel in enumerate(ideal))
    return dcg / idcg if idcg > 0 else 0.0


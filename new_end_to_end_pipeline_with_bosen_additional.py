# ── Helper functions ──
def resolve(name):
    for v in [name, name.lower(), name.replace(" ", "_"), name.lower().replace(" ", "_")]:
        if v in e2id:
            return v
    return None

def predict_head(relation, tail, top_k=500):
    t = resolve(tail)
    if not t or relation not in r2id:
        return []
    scores = -np.abs(ec * rc[r2id[relation]] - ec[e2id[t]]).sum(axis=1)
    ranked = np.argsort(-scores)
    return [(id2e[i], float(scores[i])) for i in ranked if id2e[i] != t][:top_k]

